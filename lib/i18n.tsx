const DICTS: Record<UiLang, Dict> = { en, es, fil };

export type T = (key: StrKey, vars?: Record<string, string | number>) => string;

interface Ctx {
  lang: UiLang;
  setLang: (l: UiLang) => void;
  t: T;
}

const LangCtx = createContext<Ctx | null>(null);

const STORE_KEY = "lantern.lang";

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<UiLang>("en");

  useEffect(() => {
    let saved: string | null = null;
    try {
      saved = new URLSearchParams(window.location.search).get("lang") ?? localStorage.getItem(STORE_KEY);
    } catch {
      /* storage unavailable */
    }
    // eslint-disable-next-line react-hooks/set-state-in-effect -- one-time init from URL / storage
    if (saved && saved in DICTS) setLangState(saved as UiLang);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: UiLang) => {
    setLangState(l);
    try {
      localStorage.setItem(STORE_KEY, l);
    } catch {
      /* storage unavailable */
    }
  }, []);

  const t = useCallback<T>(
    (key, vars) => {
      let s: string = DICTS[lang][key] ?? en[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
      return s;
    },
    [lang],
  );

  return <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>;
}

export function useLang() {
  const c = useContext(LangCtx);
  if (!c) throw new Error("useLang must be used inside LangProvider");
  return c;
}

export const useT = () => useLang().t;
